function lookupPhone(phone) {
  if (!phone || phone.length < 7) return '';
  const clean = phone.replace(/\D/g, '');
  const prefix7 = clean.slice(0, 7);
  const prefix4 = clean.slice(0, 4);
  if (module.exports[prefix7]) return module.exports[prefix7];
  if (areaCodeMap[prefix4]) return areaCodeMap[prefix4];
  // ★ 增强兜底：7 位精确未命中时，HLR 通常为城市区号
  // 先试 4 位区号（如 0511 镇江），再试 3 位区号（如 027 武汉）
  const hlr4 = clean.slice(3, 7);
  const hlr3 = clean.slice(3, 6);
  if (areaCodeMap[hlr4]) return areaCodeMap[hlr4];
  if (areaCodeMap[hlr3]) return areaCodeMap[hlr3];
  return '';
}

module.exports.lookup = lookupPhone;
module.exports.areaCodeMap = areaCodeMap;
